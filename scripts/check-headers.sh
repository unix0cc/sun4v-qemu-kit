#!/bin/bash
# SPDX-License-Identifier: BSD-2-Clause
# Copyright (c) 2026 sun4v-qemu-kit author(s), see the AUTHORS file
# check-headers.sh [--fix] -- every script and makefile of this project's own layer carries the two-line licence header.
# Own layer = tracked files outside src/, md/ and build/hv_reset/gnu/reference/ that start with `#!` or are
# named Makefile, Containerfile (at any depth), *.mk, *.sh, *.py, *.in, *.ac -- minus the exceptions below. --fix adds a missing header; without it, lists them (rc 1).
set -uo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/.."
SPDX='# SPDX-License-Identifier: BSD-2-Clause'
COPY='# Copyright (c) 2026 sun4v-qemu-kit author(s), see the AUTHORS file'
# configure: generated by autoconf. scripts/sync-*-guest.sh: not published.
SKIP='^(configure|scripts/sync-from-guest\.sh|scripts/sync-to-guest\.sh)$'
bad=0
while IFS= read -r f; do
  [ -f "$f" ] && [ ! -L "$f" ] || continue
  case "$f" in src/*|md/*|build/hv_reset/gnu/reference/*|PRISTINE-MANIFEST) continue;; esac
  [[ $f =~ $SKIP ]] && continue
  first=$(head -c 200 "$f" | tr -d '\0' | head -1)
  case "$first" in '#!'*) ;; *) case "$f" in Makefile|*/Makefile|Containerfile|*/Containerfile|*.mk|*.sh|*.py|*.in|*.ac) ;; *) continue;; esac;; esac
  head -5 "$f" | grep -q 'SPDX-License-Identifier: BSD-2-Clause' && continue
  if [ "${1:-}" = --fix ]; then
    c=$COPY; s=$SPDX; case "$f" in *.ac) s="dnl ${SPDX#\# }"; c="dnl ${COPY#\# }";; esac
    if [[ $first == '#!'* ]]; then sed -i "1a\\
$s\\
$c" "$f"; else sed -i "1i\\
$s\\
$c" "$f"; fi
  else
    echo "no licence header: $f"; bad=1
  fi
done < <(git ls-files)
exit $bad
