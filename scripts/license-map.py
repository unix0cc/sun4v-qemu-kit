"""license-map.py -- write LICENSE_SRC.MAP: the license text found in each file under src/.

    python3 scripts/license-map.py > LICENSE_SRC.MAP

Reads the files, decides nothing: it reports which header is in a file, not which
terms apply. Classes:
  B   Sun's "Copyright Header" (the BSD+ grant), identical in every file that has it
  BC  that header and, after it, a CDDL header
  S   a Sun copyright line only; the file carries no grant text
  N   no copyright or license text at all
  X   binary, cannot carry a header

The license column is what the file says, never a conclusion: BSD+ is Sun's header text,
CDDL-1.0 the header of that name, "none stated" a file with no grant in it.
"""
import os, re, sys, hashlib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)

# Measured for the files of class S and N (method: the "needed" paragraph below): all of them were
# removed from a copy and put back only where a build stopped. "gnu, sun": the gnu path
# and the sun path both stop without it; "sun": only the sun
# path stops; "no": neither. Files of the other classes were not measured.
NEEDED = {
    "src/hypervisor/src/support/mdgen/mdlex.l": "gnu, sun",
    "src/hypervisor/src/greatlakes/common/include/vdev_snet.h": "gnu, sun",
    "src/obp/obp/arch/sun4v/niagara/t1_fpga/Makefile": "gnu, sun",
    "src/obp/obp/arch/sun4v/niagara/t1_fpga/debug.fth": "gnu, sun",
    "src/hypervisor/src/support/aschk/aslex.l": "sun",
    "src/hypervisor/src/greatlakes/common/src/vdev_snet.s": "sun",
    "src/obp/obp/firmware.rel": "sun",
}

LICENSE = {
    "B": "BSD+ (Sun)",
    "BC": "BSD+ (Sun) + CDDL-1.0",
    "S": "none stated (Sun (c) only)",
    "N": "none stated",
    "X": "none stated (binary)",
}

def norm(block):
    out = []
    for l in block.split("\n"):
        l = re.sub(r"^\s*(\*|\\|#|!|//|/\*)+\s?", "", l).strip()
        l = re.sub(r"\s+", " ", l)
        if l.startswith("Hypervisor Software File:"):
            continue
        l = re.sub(r"\(c\) \S+", "(c) YEAR", l)
        out.append(l)
    return "\n".join(out)

def year(t):
    m = re.search(r"Copyright \(c\) (\d{4})", t) or re.search(r"(?i)copyright:? (?:\(c\) )?(\d{4})", t)
    return m.group(1) if m else "-"

SUN = {}
rows = []
for r, d, fs in os.walk("src"):
    d.sort()
    for f in sorted(fs):
        p = os.path.join(r, f)
        b = open(p, "rb").read()
        if b"\0" in b[:8192]:
            rows.append(("X", "-", p)); continue
        t = b.decode("utf8", "replace")
        head = t[:6000]
        m = re.search(r"Copyright Header Begin.*?(?:Copyright Header End|\Z)", head, re.S)
        cddl = "CDDL HEADER START" in head
        if m:
            h = hashlib.sha1(norm(m.group(0)).encode()).hexdigest()[:8]
            SUN.setdefault(h, 0); SUN[h] += 1
            rows.append(("BC" if cddl else "B", year(m.group(0)), p))
        elif re.search(r"(?i)copyright", head):
            rows.append(("S", year(head), p))
        else:
            rows.append(("N", "-", p))

count = {}
for c, y, p in rows:
    count[c] = count.get(c, 0) + 1

out = []
w = out.append
w("LICENSE_SRC.MAP -- the license text found in each file under src/")
w("=" * 62)
w("")
w("Generated by scripts/license-map.py; do not edit. It reports which header a file")
w("carries, not which terms apply: for that, LICENSE and LICENSE_CODE.")
w("")
w("    class  files  header in the file")
w("    -----  -----  --------------------------------------------------------")
for c, txt in (("B", "Sun's \"Copyright Header\" (the BSD+ grant)"),
               ("BC", "that header, and after it a CDDL header"),
               ("S", "a Sun copyright line only, no grant text"),
               ("N", "no copyright or license text"),
               ("X", "binary")):
    w("    %-5s  %5d  %s" % (c, count.get(c, 0), txt))
w("    total  %5d" % len(rows))
w("")
w("Among the %d files with that header (B and BC) there is %d distinct text%s, the year" % (
    sum(SUN.values()), len(SUN), "" if len(SUN) == 1 else "s"))
w("and the file name aside.")
w("")
w("Every file that is not class B, which is where a question about terms comes from.")
w("The \"needed\" column is measured for classes S and N only: which path stops when the")
w("file is missing; \"-\" means not measured. Method: all 20 files were removed from a copy,")
w("the files the build stopped for put back, then the reduced and the full set built into")
w("the same OUTDIR with the same SOURCE_DATE_EPOCH. All six outputs (openboot.bin, q.bin,")
w("reset.bin, 1up-md.bin, 1up-hv.bin, nvram1) were byte-identical (md5 on the Solaris side).")
w("Needed on the gnu path: 4; on the sun path (legion, Solaris 10,")
w("Sun Studio 11): 7 -- the four, and aschk/aslex.l, vdev_snet.s, obp/firmware.rel.")
w("One sun-path run stopped at mmu_common.o with no message in the log; the same command")
w("passed on the next run. Not explained.")
w("")
w("    class  license                      needed    year  path")
def needed(c, p):
    if c in ("S", "N"):
        return NEEDED.get(p, "no")
    return "-"
for c, y, p in rows:
    if c != "B":
        w("    %-5s  %-27s  %-8s  %-4s  %s" % (c, LICENSE[c], needed(c, p), y, p))
w("")
w("All files")
w("---------")
w("    class  license                      needed    year  path")
for c, y, p in rows:
    w("    %-5s  %-27s  %-8s  %-4s  %s" % (c, LICENSE[c], needed(c, p), y, p))
sys.stdout.write("\n".join(out) + "\n")
